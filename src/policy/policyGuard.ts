import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, renameSync, statSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

// Overwrite protection for the generated privacy policy. Every policy SrcLawyer writes ends with a
// marker line holding a SHA-256 of the rest of the file. Before writing over an existing file we
// recompute that hash: a match means nobody has touched it since we generated it (safe to
// regenerate); anything else means it is someone's work and is left alone unless --force is passed.
// This detects changes, it is not a security feature -- anyone can recompute the hash.

const MARKER_PREFIX = "<!-- srclawyer:policy-sha256=";
const MARKER_LINE = /^<!-- srclawyer:policy-sha256=([0-9a-f]{64}) -->$/;

/** Where `scan` writes the policy unless told otherwise. */
export const DEFAULT_POLICY_PATH = "PRIVACY_POLICY.md";

/** The path suggested for a side-by-side draft when the real policy is protected. */
export const SUGGESTED_DRAFT_PATH = "PRIVACY_POLICY.generated.md";

// CRLF/CR become LF and trailing whitespace is dropped, so a Windows checkout (autocrlf) or an editor
// that adds or strips the final newline is not mistaken for a hand edit.
function normalize(text: string): string {
  return text.replace(/\r\n?/g, "\n").trimEnd();
}

function sha256(text: string): string {
  return createHash("sha256").update(text, "utf8").digest("hex");
}

/** Appends the marker line to a freshly generated policy. */
export function withPolicyMarker(body: string): string {
  const terminated = body.endsWith("\n") ? body : `${body}\n`;
  return `${terminated}${MARKER_PREFIX}${sha256(normalize(body))} -->\n`;
}

export type PolicyFileState = "missing" | "unchanged" | "edited" | "unmarked";

/** What an existing file at `path` is, relative to what SrcLawyer last generated. */
export function classifyPolicyFile(path: string): PolicyFileState {
  if (!existsSync(path)) return "missing";
  const lines = readFileSync(path, "utf8").replace(/\r\n?/g, "\n").split("\n");
  let markerIndex = -1;
  let recorded = "";
  for (let i = lines.length - 1; i >= 0; i--) {
    const match = MARKER_LINE.exec(lines[i]!.trim());
    if (match) {
      markerIndex = i;
      recorded = match[1]!;
      break;
    }
  }
  if (markerIndex === -1) return "unmarked";
  // Everything except the marker line counts, including text added after it.
  const rest = lines.filter((_, i) => i !== markerIndex).join("\n");
  return sha256(normalize(rest)) === recorded ? "unchanged" : "edited";
}

export type PolicyWriteDecision =
  | { allowed: true }
  | { allowed: false; kind: "edited" | "unmarked"; message: string };

function alternativeOut(path: string): string {
  return path === SUGGESTED_DRAFT_PATH ? "a different path" : SUGGESTED_DRAFT_PATH;
}

export function editedMessage(path: string): string {
  return `Not overwriting ${path}: it has been edited since SrcLawyer generated it. Write the new policy to a separate file with --out ${alternativeOut(path)} and compare, or pass --force to replace it.`;
}

export function unmarkedMessage(path: string): string {
  return `Not overwriting ${path}: it was not generated by this version of SrcLawyer (it may be hand-written, or generated before overwrite protection was added in 0.8.0). Write the new policy to a separate file with --out ${alternativeOut(path)} and compare, or pass --force to replace it.`;
}

/** Whether `scan` may write its policy to `path`. `displayPath` is the path as the user gave it. */
export function checkPolicyWrite(path: string, displayPath: string, force: boolean): PolicyWriteDecision {
  if (force) return { allowed: true };
  // A directory is not a policy file; let the write fail the way it always has.
  if (existsSync(path) && statSync(path).isDirectory()) return { allowed: true };
  const state = classifyPolicyFile(path);
  if (state === "edited") return { allowed: false, kind: "edited", message: editedMessage(displayPath) };
  if (state === "unmarked") return { allowed: false, kind: "unmarked", message: unmarkedMessage(displayPath) };
  return { allowed: true };
}

/** The first 8 hex characters of a marked file's recorded hash, or null when it has no marker. */
export function markerHash(content: string, length = 8): string | null {
  const lines = content.replace(/\r\n?/g, "\n").split("\n");
  for (let i = lines.length - 1; i >= 0; i--) {
    const match = MARKER_LINE.exec(lines[i]!.trim());
    if (match) return match[1]!.slice(0, length);
  }
  return null;
}

export interface MarkedWrite {
  path: string;
  written: boolean;
  /** Set when the write was skipped because the existing file is edited or wasn't generated by SrcLawyer. */
  skippedReason: "edited" | "unmarked" | null;
}

/**
 * Writes a generated artifact (a draft policy, a review file) with the end marker, but only over a
 * missing file or one whose marker still matches -- the same guard as the policy itself. Written via a
 * temporary file and rename so a reader never sees half a file.
 */
export function writeMarkedFile(absPath: string, displayPath: string, body: string): MarkedWrite {
  const state = classifyPolicyFile(absPath);
  if (state === "edited" || state === "unmarked") return { path: displayPath, written: false, skippedReason: state };
  mkdirSync(dirname(absPath), { recursive: true });
  const tmp = `${absPath}.${process.pid}.tmp`;
  writeFileSync(tmp, withPolicyMarker(body));
  renameSync(tmp, absPath);
  return { path: displayPath, written: true, skippedReason: null };
}
